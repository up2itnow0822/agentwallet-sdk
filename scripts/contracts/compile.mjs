import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import solc from 'solc';

export const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
export function compileContracts(includeTests = false) {
  const names = ['contracts/AgentVault.sol', ...(includeTests ? ['tests/contracts/Adversaries.sol'] : [])];
  const sources = Object.fromEntries(names.map(name => [name, { content: readFileSync(resolve(root, name), 'utf8') }]));
  const input = { language: 'Solidity', sources, settings: {
    optimizer: { enabled: true, runs: 200 }, evmVersion: 'cancun',
    metadata: { bytecodeHash: 'none', appendCBOR: false },
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object', 'evm.deployedBytecode.immutableReferences'] } },
  } };
  const output = JSON.parse(solc.compile(JSON.stringify(input), { import: name => {
    if (!name.startsWith('@openzeppelin/contracts/') || name.includes('..')) return { error: 'Unsupported import' };
    try { return { contents: readFileSync(resolve(root, 'node_modules', name), 'utf8') }; }
    catch { return { error: `Missing dependency: ${name}` }; }
  } }));
  const errors = (output.errors ?? []).filter(error => error.severity === 'error');
  if (errors.length) throw new Error(errors.map(error => error.formattedMessage).join('\n'));
  return { compiler: solc.version(), settings: input.settings, contracts: output.contracts };
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const compiled = compileContracts(process.argv.includes('--tests'));
  const vault = compiled.contracts['contracts/AgentVault.sol'].AgentVault;
  mkdirSync(resolve(root, 'src/contracts'), { recursive: true });
  mkdirSync(resolve(root, 'artifacts/contracts'), { recursive: true });
  writeFileSync(resolve(root, 'src/contracts/AgentVaultAbi.ts'), `// Generated by scripts/contracts/compile.mjs; do not edit.\n// AgentVault and OpenZeppelin dependency license: MIT.\nexport const AgentVaultAbi = ${JSON.stringify(vault.abi, null, 2)} as const;\n`);
  writeFileSync(resolve(root, 'src/contracts/AgentVaultBytecode.ts'), `// Generated by scripts/contracts/compile.mjs; do not edit.\n// Solidity ${compiled.compiler}; Cancun; optimizer 200 runs.\n// AgentVault and OpenZeppelin dependency license: MIT.\nexport const AgentVaultBytecode = '0x${vault.evm.bytecode.object}' as const;\n`);
  writeFileSync(resolve(root, 'artifacts/contracts/compiled.json'), JSON.stringify(compiled, null, 2) + '\n');
  console.log(`Compiled AgentVault using ${compiled.compiler}; deterministic ABI exported (${vault.abi.length} entries).`);
}
